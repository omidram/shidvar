type CityRow = { name: string; lat: number; lng: number };

function parseCities(): CityRow[] {
  const seen = new Set<string>();
  const out: CityRow[] = [];
  for (const line of RAW.split("\n")) {
    const [name, lat, lng] = line.split(",");
    if (!name || seen.has(name)) continue;
    seen.add(name);
    out.push({ name, lat: Number(lat), lng: Number(lng) });
  }
  out.sort((a, b) => a.name.localeCompare(b.name, "fa"));
  return out;
}

